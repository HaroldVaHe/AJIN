-- ------------------------------------------------------------
-- 1) Roles y permisos
-- ------------------------------------------------------------
-- Un usuario entra al panel si su email está en ADMIN_EMAILS (rol admin)
-- o si existe una fila aquí. Los permisos de cada rol se editan desde
-- /admin/roles y viven en role_permissions.
create table if not exists public.user_roles (
  email text primary key,
  role text not null default 'gestor',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint user_roles_email_lower check (email = lower(email))
);

create table if not exists public.role_permissions (
  role text not null,
  permission text not null,
  primary key (role, permission)
);

alter table public.user_roles enable row level security;
alter table public.role_permissions enable row level security;
-- Sin políticas: solo la service-role key (rutas /api/admin/*) puede leer/escribir.

insert into public.role_permissions (role, permission) values
  ('admin',  'properties.manage'),
  ('admin',  'properties.delete'),
  ('admin',  'leases.manage'),
  ('admin',  'leases.finance'),
  ('admin',  'audit.view'),
  ('admin',  'roles.manage'),
  ('gestor', 'properties.manage'),
  ('gestor', 'properties.delete'),
  ('gestor', 'leases.manage'),
  ('gestor', 'leases.finance'),
  ('gestor', 'audit.view')
on conflict do nothing;

-- ------------------------------------------------------------
-- 2) Contratos de arriendo
-- ------------------------------------------------------------
create table if not exists public.leases (
  id bigint generated by default as identity primary key,
  property_id bigint not null references public.properties(id) on delete cascade,

  tenant_name text not null,
  tenant_phone text not null,
  tenant_email text not null default '',
  tenant_document text not null default '',

  owner_name text not null,
  owner_phone text not null,
  owner_email text not null default '',
  owner_document text not null default '',

  -- Canon mensual y administración del conjunto (ambos los cobra la inmobiliaria).
  rent_cop bigint not null check (rent_cop >= 0),
  building_fee_cop bigint not null default 0 check (building_fee_cop >= 0),

  -- Comisión de gestión: porcentaje sobre el canon o monto fijo en COP.
  agency_mode text not null default 'percent' check (agency_mode in ('percent', 'fixed')),
  agency_value numeric(12, 2) not null default 10 check (agency_value >= 0),

  payment_day int not null default 1 check (payment_day between 1 and 28),
  reminder_days int[] not null default '{5,1}',
  start_date date not null,
  end_date date,
  status text not null default 'active' check (status in ('active', 'finished')),
  notes text not null default '',

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Conceptos recurrentes del contrato (parqueadero, agua, luz, etc.).
-- charge_tenant = se suma al cobro mensual del inquilino.
-- deduct_owner = se descuenta del giro al propietario.
create table if not exists public.lease_concepts (
  id bigint generated by default as identity primary key,
  lease_id bigint not null references public.leases(id) on delete cascade,
  name text not null,
  amount_cop bigint not null default 0 check (amount_cop >= 0),
  charge_tenant boolean not null default true,
  deduct_owner boolean not null default false,
  active boolean not null default true,
  position int not null default 0,
  created_at timestamptz not null default now()
);

-- Mensualidades. Guardan una foto de los valores al generarse: editar el
-- contrato después no reescribe meses ya causados (solo los no pagados).
create table if not exists public.lease_periods (
  id bigint generated by default as identity primary key,
  lease_id bigint not null references public.leases(id) on delete cascade,
  period text not null,                 -- 'YYYY-MM'
  due_date date not null,

  rent_cop bigint not null default 0,
  building_cop bigint not null default 0,
  agency_cop bigint not null default 0,
  extras_tenant_cop bigint not null default 0,
  extras_owner_cop bigint not null default 0,
  total_due_cop bigint not null default 0,   -- a cobrar al inquilino
  owner_payout_cop bigint not null default 0, -- a girar al propietario

  paid_cop bigint not null default 0 check (paid_cop >= 0),
  status text not null default 'pending' check (status in ('pending', 'partial', 'paid')),
  paid_at date,
  payout_paid_at date,
  notes text not null default '',

  -- Recordatorios: 0 = ninguno, 1 = próximo, 2 = vence hoy, 3 = vencido.
  reminder_stage int not null default 0,
  reminded_on date,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (lease_id, period)
);

-- Cuentas de cobro / facturas / soportes de pago.
create table if not exists public.lease_receipts (
  id bigint generated by default as identity primary key,
  lease_id bigint not null references public.leases(id) on delete cascade,
  period_id bigint references public.lease_periods(id) on delete set null,
  kind text not null default 'other'
    check (kind in ('invoice', 'payment', 'building', 'utility', 'payout', 'other')),
  label text not null default '',
  amount_cop bigint,
  path text not null,
  created_at timestamptz not null default now()
);

alter table public.leases enable row level security;
alter table public.lease_concepts enable row level security;
alter table public.lease_periods enable row level security;
alter table public.lease_receipts enable row level security;
-- Sin políticas públicas: la información financiera solo se sirve por
-- rutas /api/admin/* con la service-role key y sesión autorizada.

create index if not exists leases_property_idx on public.leases (property_id);
create index if not exists lease_periods_lease_idx on public.lease_periods (lease_id, period);
create index if not exists lease_periods_due_idx on public.lease_periods (due_date);
create index if not exists lease_receipts_lease_idx on public.lease_receipts (lease_id);

-- Un inmueble no puede tener dos contratos activos a la vez.
create unique index if not exists leases_one_active_per_property
  on public.leases (property_id)
  where status = 'active';

